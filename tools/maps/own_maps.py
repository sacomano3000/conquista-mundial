#!/usr/bin/env python3
"""The registry of this game's own maps (src/shared/Data/MapList.luau), written by whichever of the
map builders ran last: make_fantasy_world.py (Eldoria, the world) and make_small_map.py (Valtara, the
small one). Each builder gives its own row; the other maps' rows are read back from their modules, so
building one map never drops another from the list.
"""
import os

import make_maps as M

#: every own map: what the registry says about it (the builders add width / height / land / kingdoms)
SPECS = {
    "world": dict(id="world", name="Eldoria", module="World", world=True,
                  categories=["featured", "world"], frequency=30, modifiers=["isCrowded:50"]),
    "valtara": dict(id="valtara", name="Valtara", module="Valtara",
                    categories=["featured", "small"], frequency=30, modifiers=[]),
}


class Size:
    def __init__(self, w, h):
        self.w, self.h = w, h


def write_registry(built):
    """built: [(spec, proj, land_tiles, kingdoms)] of the maps made in this run."""
    rows = list(built)
    done = {r[0]["id"] for r in rows}
    for key, spec in SPECS.items():
        if key in done or not os.path.exists(M.module_path(spec)):
            continue
        w, h, land, nations = M.read_row(spec)
        rows.append((spec, Size(w, h), land, nations))
    M.LICENSE, M.ATTRIBUTION, M.CREDITS = "Original", "", ""
    M.write_registry(rows)
    reg = os.path.join(M.REPO, "src", "shared", "Data", "MapList.luau")
    s = open(reg, encoding="utf-8").read()
    s = s.replace("-- GENERATED by tools/maps/make_maps.py. Do not edit.",
                  "-- GENERATED by tools/maps/make_fantasy_world.py and make_small_map.py (own_maps.py). Do not edit.")
    s = s.replace("except World, replicated in src/shared/Data/Maps/World.luau so the title",
                  "except World (Eldoria), replicated in src/shared/Data/Maps/World.luau so the title")
    open(reg, "w", encoding="utf-8").write(s)
    return rows
